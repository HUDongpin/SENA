import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const projectRoot = process.cwd();
const envPath = resolve(projectRoot, ".env.local");
const enterpriseDbDir = resolve(projectRoot, ".sena-enterprise");
const appUrl = process.env.SENA_SELF_MANAGED_APP_URL ?? "http://127.0.0.1:3101";

const secretKeys = new Set([
  "SENA_OPS_TOKEN",
  "SENA_SESSION_SECRET",
  "SENA_CSRF_SECRET",
  "SENA_MFA_ENCRYPTION_KEY"
]);

function randomSecret() {
  return randomBytes(32).toString("base64url");
}

function parseEnvFile(path) {
  if (!existsSync(path)) return new Map();
  const entries = new Map();
  for (const rawLine of readFileSync(path, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const separator = line.indexOf("=");
    if (separator === -1) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith("\"") && value.endsWith("\"")) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (key) entries.set(key, value);
  }
  return entries;
}

function envLine(key, value) {
  const printable = /^[A-Za-z0-9_./:@+-]+$/.test(value)
    ? value
    : JSON.stringify(value);
  return `${key}=${printable}`;
}

mkdirSync(enterpriseDbDir, { recursive: true });

const existing = parseEnvFile(envPath);
const desired = new Map([
  ["SENA_ENTERPRISE_DEPLOYMENT_MODE", "self-managed"],
  ["SENA_SELF_MANAGED_WEBHOOK_SINK", "local"],
  ["SENA_ENTERPRISE_DB_DIR", enterpriseDbDir],
  ["SENA_APP_URL", appUrl],
  ["SENA_OPS_TOKEN", existing.get("SENA_OPS_TOKEN") ?? randomSecret()],
  ["SENA_SESSION_SECRET", existing.get("SENA_SESSION_SECRET") ?? randomSecret()],
  ["SENA_CSRF_SECRET", existing.get("SENA_CSRF_SECRET") ?? randomSecret()],
  ["SENA_MFA_ENCRYPTION_KEY", existing.get("SENA_MFA_ENCRYPTION_KEY") ?? randomSecret()],
  ["SENA_AUDIT_RETENTION_DAYS", "3650"],
  ["SENA_ALERTING_OWNER", "SENA self-managed operator"],
  ["SENA_ALERTING_CHANNEL", "local-ops"],
  ["SENA_ALERTING_RUNBOOK_URL", `${appUrl}/workspace/sena`]
]);

for (const [key, value] of existing) {
  if (!desired.has(key)) desired.set(key, value);
}

const lines = [
  "# Generated by npm run sena:self-managed:env.",
  "# Secret values are local-only and must not be committed or printed.",
  "",
  ...Array.from(desired.entries()).map(([key, value]) => envLine(key, value)),
  ""
];

writeFileSync(envPath, lines.join("\n"), "utf8");

const report = Array.from(desired.keys()).map((key) => {
  const value = secretKeys.has(key) ? "configured(redacted)" : desired.get(key);
  return `  ${key}=${value}`;
});

console.log(`Wrote self-managed SENA local environment to ${envPath}`);
console.log(`Ensured enterprise data directory ${enterpriseDbDir}`);
console.log("Configured keys:");
console.log(report.join("\n"));
